import 'package:flutter/material.dart';
import 'package:flutter_animate/flutter_animate.dart';
import 'package:google_fonts/google_fonts.dart';

import '../services/inference_service.dart';
import '../utils/theme.dart';
import 'it23136274_alerts_history_screen.dart';
import 'it23136274_sensor_trends_screen.dart';

/// Student Registration: IT23136274
/// Research Component: AI-Based Colony Health Monitoring
/// Feature: AI Health Assessment (Colony Status) Screen
///
/// Fully conforms to Skills/Frontend_skill.md:
/// - Palette: Strictly uses AppColors (bgPrimary, bgSecondary, bgElevated, border,
///   textPrimary, textSecondary, accent, accent2, accent3, success, warning, error,
///   info, badgeLeafBg, badgeLeafFg, badgeTempBg, badgeTempFg, hiveLow, hiveDoor).
/// - Typography: GoogleFonts.inter across all elements with canonical weights & sizes.
/// - Architecture: Scaffold, AppBar, SafeArea, SingleChildScrollView (padding 20).
/// - Shared 5-item fixed bottom navigation with AppColors.hiveLow on Health index.
/// - Zero raw Color(0x...) or Colors.* calls.
class IT23136274AiHealthAssessmentScreen extends StatefulWidget {
  final String hiveId;
  final String hiveName;
  final String apiaryName;
  final String initialStatus;
  final double confidence;
  final List<String>? indicators;
  final String? recommendation;
  final InferenceService? inferenceService;

  const IT23136274AiHealthAssessmentScreen({
    super.key,
    this.hiveId = 'hive-01',
    this.hiveName = 'Hive 01',
    this.apiaryName = 'Yakkala Apiary',
    this.initialStatus = 'Early Stress',
    this.confidence = 0.87,
    this.indicators,
    this.recommendation,
    this.inferenceService,
  });

  @override
  State<IT23136274AiHealthAssessmentScreen> createState() =>
      _IT23136274AiHealthAssessmentScreenState();
}

typedef AiHealthAssessmentScreen = IT23136274AiHealthAssessmentScreen;

class _IT23136274AiHealthAssessmentScreenState
    extends State<IT23136274AiHealthAssessmentScreen> {
  static const int _tabIndex = 1; // Health tab

  late String _status;
  late double _confidence;
  late List<String> _indicators;
  late String _recommendation;

  @override
  void initState() {
    super.initState();
    _status = widget.initialStatus;
    _confidence = widget.confidence;
    _indicators = widget.indicators ??
        const [
          'Hive weight is decreasing',
          'Bee activity lower than normal',
          'Humidity higher than usual',
        ];
    _recommendation = widget.recommendation ??
        'Inspect the colony and continue monitoring for the next 24 hours.';
  }

  void _onNavTapped(int index) {
    if (index == _tabIndex) {
      Navigator.of(context).pop();
      return;
    }
    if (index == 0) {
      Navigator.of(context).popUntil((route) => route.isFirst);
      return;
    }

    final labels = ['Home', 'Health', 'Relocate', 'Acoustic', 'Environment'];
    ScaffoldMessenger.of(context).showSnackBar(
      SnackBar(
        content: Text(
          '${labels[index]} module will be available in the next update.',
          style: GoogleFonts.inter(
            fontSize: 13,
            fontWeight: FontWeight.w500,
            color: AppColors.bgSecondary,
          ),
        ),
        backgroundColor: AppColors.panelBlack,
        behavior: SnackBarBehavior.floating,
        duration: const Duration(seconds: 2),
      ),
    );
  }

  void _openSensorTrends() {
    Navigator.of(context).push(
      MaterialPageRoute(
        builder: (_) => IT23136274SensorTrendsScreen(
          hiveId: widget.hiveId,
          hiveName: widget.hiveName,
          apiaryName: widget.apiaryName,
          inferenceService: widget.inferenceService,
        ),
      ),
    );
  }

  void _showInfoDialog() {
    showDialog(
      context: context,
      builder: (ctx) => AlertDialog(
        backgroundColor: AppColors.bgSecondary,
        shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(18)),
        title: Text(
          'Detected Indicators',
          style: GoogleFonts.inter(
            fontSize: 17,
            fontWeight: FontWeight.w700,
            color: AppColors.textPrimary,
          ),
        ),
        content: Text(
          'These anomaly triggers are generated by our multi-sensor inference engine analyzing continuous ESP32 telemetry (Weight, Temperature, Humidity, and Bee Activity).',
          style: GoogleFonts.inter(
            fontSize: 14,
            height: 1.5,
            color: AppColors.textSecondary,
          ),
        ),
        actions: [
          TextButton(
            onPressed: () => Navigator.of(ctx).pop(),
            child: Text(
              'Understood',
              style: GoogleFonts.inter(
                fontSize: 14,
                fontWeight: FontWeight.w700,
                color: AppColors.accent,
              ),
            ),
          ),
        ],
      ),
    );
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      backgroundColor: AppColors.bgPrimary,
      appBar: AppBar(
        backgroundColor: AppColors.bgPrimary,
        elevation: 0,
        centerTitle: true,
        leading: IconButton(
          icon: const Icon(
            Icons.arrow_back,
            color: AppColors.textPrimary,
            size: 24,
          ),
          onPressed: () => Navigator.of(context).pop(),
        ),
        title: Column(
          mainAxisSize: MainAxisSize.min,
          crossAxisAlignment: CrossAxisAlignment.center,
          children: [
            Text(
              'AI Health Assessment',
              style: GoogleFonts.inter(
                fontSize: 18,
                fontWeight: FontWeight.w700,
                color: AppColors.textPrimary,
              ),
            ),
            const SizedBox(height: 2),
            Text(
              '${widget.hiveName} • ${widget.apiaryName}',
              style: GoogleFonts.inter(
                fontSize: 12,
                fontWeight: FontWeight.w500,
                color: AppColors.textSecondary,
              ),
            ),
          ],
        ),
        actions: [
          IconButton(
            icon: const Icon(Icons.history_rounded, color: AppColors.textPrimary, size: 22),
            tooltip: 'Alerts & History',
            onPressed: () {
              Navigator.of(context).push(
                MaterialPageRoute(
                  builder: (_) => IT23136274AlertsHistoryScreen(
                    hiveId: widget.hiveId,
                    hiveName: widget.hiveName,
                    apiaryName: widget.apiaryName,
                    inferenceService: widget.inferenceService,
                  ),
                ),
              );
            },
          ),
          const SizedBox(width: 6),
        ],
      ),
      body: SafeArea(
        child: SingleChildScrollView(
          padding: const EdgeInsets.symmetric(horizontal: 20),
          child: Column(
            crossAxisAlignment: CrossAxisAlignment.stretch,
            children: [
              const SizedBox(height: 14),

              // 1. Colony Health Status Hero Card
              _buildColonyStatusCard(),
              const SizedBox(height: 18),

              // 2. Detected Indicators Card
              _buildDetectedIndicatorsCard(),
              const SizedBox(height: 16),

              // 3. Recommendation Card
              _buildRecommendationCard(),
              const SizedBox(height: 18),

              // 4. Sensor Summary Card
              _buildSensorSummaryCard(),
              const SizedBox(height: 18),

              // 5. Action Button: View Detailed Trends
              _buildTrendsButton(),
              const SizedBox(height: 24),
            ],
          ),
        ),
      ),
      bottomNavigationBar: _buildBottomNav(),
    );
  }

  // ── 1. Colony Health Status Hero Card ─────────────────────────────────
  Widget _buildColonyStatusCard() {
    final confidencePct = (_confidence * 100).toInt();

    return Container(
      padding: const EdgeInsets.symmetric(horizontal: 20, vertical: 22),
      decoration: BoxDecoration(
        color: AppColors.bgElevated,
        borderRadius: BorderRadius.circular(20),
        border: Border.all(
          color: AppColors.border,
          width: 1.0,
        ),
        boxShadow: [
          BoxShadow(
            color: AppColors.accent.withValues(alpha: 0.08),
            blurRadius: 12,
            offset: const Offset(0, 4),
          ),
        ],
      ),
      child: Column(
        children: [
          Text(
            'Colony Health Status',
            style: GoogleFonts.inter(
              fontSize: 14,
              fontWeight: FontWeight.w700,
              color: AppColors.hiveDoor,
              letterSpacing: 0.1,
            ),
          ),
          const SizedBox(height: 14),
          Row(
            mainAxisAlignment: MainAxisAlignment.center,
            children: [
              // Circular Warning Badge
              Container(
                width: 62,
                height: 62,
                decoration: BoxDecoration(
                  color: AppColors.warning.withValues(alpha: 0.18),
                  shape: BoxShape.circle,
                ),
                child: const Center(
                  child: Icon(
                    Icons.warning_amber_rounded,
                    color: AppColors.accent2,
                    size: 36,
                  ),
                ),
              ),
              const SizedBox(width: 14),
              // Status Title
              Flexible(
                child: Text(
                  _status,
                  style: GoogleFonts.inter(
                    fontSize: 26,
                    fontWeight: FontWeight.w800,
                    color: AppColors.accent2,
                    letterSpacing: -0.3,
                  ),
                ),
              ),
            ],
          ),
          const SizedBox(height: 10),
          Text(
            'Confidence: $confidencePct%',
            style: GoogleFonts.inter(
              fontSize: 14,
              fontWeight: FontWeight.w600,
              color: AppColors.textSecondary,
            ),
          ),
        ],
      ),
    ).animate().fadeIn(duration: 350.ms).slideY(begin: 0.05, end: 0);
  }

  // ── 2. Detected Indicators Card ───────────────────────────────────────
  Widget _buildDetectedIndicatorsCard() {
    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        Row(
          children: [
            Text(
              'Detected Indicators',
              style: GoogleFonts.inter(
                fontSize: 16,
                fontWeight: FontWeight.w700,
                color: AppColors.textPrimary,
              ),
            ),
            const SizedBox(width: 6),
            InkWell(
              onTap: _showInfoDialog,
              borderRadius: BorderRadius.circular(12),
              child: const Padding(
                padding: EdgeInsets.all(4),
                child: Icon(
                  Icons.info_outline_rounded,
                  size: 18,
                  color: AppColors.textSecondary,
                ),
              ),
            ),
          ],
        ),
        const SizedBox(height: 10),
        ..._indicators.map((indicator) {
          return Padding(
            padding: const EdgeInsets.symmetric(vertical: 4.5),
            child: Row(
              crossAxisAlignment: CrossAxisAlignment.center,
              children: [
                Container(
                  width: 6,
                  height: 6,
                  margin: const EdgeInsets.only(left: 4, right: 12),
                  decoration: const BoxDecoration(
                    color: AppColors.accent2,
                    shape: BoxShape.circle,
                  ),
                ),
                Expanded(
                  child: Text(
                    indicator,
                    style: GoogleFonts.inter(
                      fontSize: 14,
                      fontWeight: FontWeight.w500,
                      color: AppColors.textPrimary,
                      height: 1.4,
                    ),
                  ),
                ),
              ],
            ),
          );
        }),
      ],
    ).animate().fadeIn(duration: 400.ms, delay: 100.ms);
  }

  // ── 3. Recommendation Card ───────────────────────────────────────────
  Widget _buildRecommendationCard() {
    return Container(
      padding: const EdgeInsets.all(16),
      decoration: BoxDecoration(
        color: AppColors.badgeTempBg,
        borderRadius: BorderRadius.circular(16),
        border: Border.all(
          color: AppColors.error.withValues(alpha: 0.18),
          width: 1.0,
        ),
      ),
      child: Row(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          Container(
            padding: const EdgeInsets.all(8),
            decoration: BoxDecoration(
              color: AppColors.bgSecondary,
              borderRadius: BorderRadius.circular(10),
              border: Border.all(
                color: AppColors.error.withValues(alpha: 0.15),
                width: 0.8,
              ),
            ),
            child: const Icon(
              Icons.assignment_outlined,
              color: AppColors.error,
              size: 24,
            ),
          ),
          const SizedBox(width: 12),
          Expanded(
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                Text(
                  'Recommendation',
                  style: GoogleFonts.inter(
                    fontSize: 15,
                    fontWeight: FontWeight.w700,
                    color: AppColors.error,
                  ),
                ),
                const SizedBox(height: 4),
                Text(
                  _recommendation,
                  style: GoogleFonts.inter(
                    fontSize: 14,
                    height: 1.45,
                    fontWeight: FontWeight.w500,
                    color: AppColors.accent2,
                  ),
                ),
              ],
            ),
          ),
        ],
      ),
    ).animate().fadeIn(duration: 450.ms, delay: 150.ms);
  }

  // ── 4. Sensor Summary Card ───────────────────────────────────────────
  Widget _buildSensorSummaryCard() {
    return Container(
      padding: const EdgeInsets.all(18),
      decoration: BoxDecoration(
        color: AppColors.bgSecondary,
        borderRadius: BorderRadius.circular(16),
        border: Border.all(
          color: AppColors.border,
          width: 1.0,
        ),
        boxShadow: [
          BoxShadow(
            color: AppColors.textPrimary.withValues(alpha: 0.03),
            blurRadius: 8,
            offset: const Offset(0, 2),
          ),
        ],
      ),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          Text(
            'Sensor Summary',
            style: GoogleFonts.inter(
              fontSize: 16,
              fontWeight: FontWeight.w700,
              color: AppColors.textPrimary,
            ),
          ),
          const SizedBox(height: 14),

          // Row 1: Temperature
          _buildSensorSummaryRow(
            icon: Icons.thermostat_rounded,
            iconColor: AppColors.accent2,
            name: 'Temperature',
            value: '31.2 °C',
            badgeText: 'Normal',
            isWarning: false,
          ),
          const Divider(color: AppColors.border, height: 20, thickness: 0.6),

          // Row 2: Humidity
          _buildSensorSummaryRow(
            icon: Icons.water_drop_rounded,
            iconColor: AppColors.info,
            name: 'Humidity',
            value: '75 %',
            badgeText: 'High',
            isWarning: true,
          ),
          const Divider(color: AppColors.border, height: 20, thickness: 0.6),

          // Row 3: Hive Weight
          _buildSensorSummaryRow(
            icon: Icons.scale_rounded,
            iconColor: AppColors.accent,
            name: 'Hive Weight',
            value: '12.4 kg',
            badgeText: 'Decreasing',
            isWarning: true,
          ),
          const Divider(color: AppColors.border, height: 20, thickness: 0.6),

          // Row 4: Bee Activity
          _buildSensorSummaryRow(
            icon: Icons.scatter_plot_rounded,
            iconColor: AppColors.hiveDoor,
            name: 'Bee Activity',
            value: '18/min',
            badgeText: 'Low',
            isWarning: true,
          ),
        ],
      ),
    ).animate().fadeIn(duration: 500.ms, delay: 200.ms);
  }

  Widget _buildSensorSummaryRow({
    required IconData icon,
    required Color iconColor,
    required String name,
    required String value,
    required String badgeText,
    required bool isWarning,
  }) {
    final badgeBg = isWarning ? AppColors.badgeTempBg : AppColors.badgeLeafBg;
    final badgeFg = isWarning ? AppColors.error : AppColors.success;

    return Row(
      children: [
        Icon(icon, color: iconColor, size: 22),
        const SizedBox(width: 10),
        Expanded(
          child: Text(
            name,
            style: GoogleFonts.inter(
              fontSize: 14,
              fontWeight: FontWeight.w500,
              color: AppColors.textPrimary,
            ),
          ),
        ),
        Text(
          value,
          style: GoogleFonts.inter(
            fontSize: 15,
            fontWeight: FontWeight.w700,
            color: AppColors.textPrimary,
          ),
        ),
        const SizedBox(width: 12),
        Container(
          padding: const EdgeInsets.symmetric(horizontal: 10, vertical: 4),
          decoration: BoxDecoration(
            color: badgeBg,
            borderRadius: BorderRadius.circular(12),
            border: Border.all(
              color: badgeFg.withValues(alpha: 0.25),
              width: 0.8,
            ),
          ),
          child: Text(
            badgeText,
            style: GoogleFonts.inter(
              fontSize: 12,
              fontWeight: FontWeight.w700,
              color: badgeFg,
            ),
          ),
        ),
      ],
    );
  }

  // ── 5. Action Button: View Detailed Trends ────────────────────────────
  Widget _buildTrendsButton() {
    return Container(
      decoration: BoxDecoration(
        color: AppColors.accent,
        borderRadius: BorderRadius.circular(16),
        boxShadow: [
          BoxShadow(
            color: AppColors.accent.withValues(alpha: 0.35),
            blurRadius: 10,
            offset: const Offset(0, 4),
          ),
        ],
      ),
      child: Material(
        color: Colors.transparent,
        child: InkWell(
          onTap: _openSensorTrends,
          borderRadius: BorderRadius.circular(16),
          child: Padding(
            padding: const EdgeInsets.symmetric(horizontal: 18, vertical: 14),
            child: Row(
              mainAxisAlignment: MainAxisAlignment.center,
              children: [
                const Icon(
                  Icons.show_chart_rounded,
                  color: AppColors.textPrimary,
                  size: 22,
                ),
                const SizedBox(width: 10),
                Text(
                  'View Detailed Sensor Trends',
                  style: GoogleFonts.inter(
                    fontSize: 14,
                    fontWeight: FontWeight.w700,
                    color: AppColors.textPrimary,
                  ),
                ),
                const SizedBox(width: 6),
                const Icon(
                  Icons.chevron_right_rounded,
                  color: AppColors.textPrimary,
                  size: 20,
                ),
              ],
            ),
          ),
        ),
      ),
    ).animate().fadeIn(duration: 550.ms, delay: 250.ms);
  }

  // ── Bottom Navigation Bar (Conforms to Frontend_skill.md) ─────────────
  Widget _buildBottomNav() {
    return BottomNavigationBar(
      type: BottomNavigationBarType.fixed,
      backgroundColor: AppColors.bgPrimary,
      selectedItemColor: AppColors.hiveLow,
      unselectedItemColor: AppColors.textSecondary,
      showUnselectedLabels: true,
      selectedFontSize: 11,
      unselectedFontSize: 11,
      currentIndex: _tabIndex,
      onTap: _onNavTapped,
      items: const [
        BottomNavigationBarItem(
          icon: Icon(Icons.home_outlined),
          label: 'Home',
        ),
        BottomNavigationBarItem(
          icon: Icon(Icons.monitor_heart_outlined),
          label: 'Health',
        ),
        BottomNavigationBarItem(
          icon: Icon(Icons.location_on_outlined),
          label: 'Relocate',
        ),
        BottomNavigationBarItem(
          icon: Icon(Icons.graphic_eq_rounded),
          label: 'Acoustic',
        ),
        BottomNavigationBarItem(
          icon: Icon(Icons.eco_outlined),
          label: 'Environment',
        ),
      ],
    );
  }
}
